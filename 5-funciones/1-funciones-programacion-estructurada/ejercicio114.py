def calcularCuadrado():
    valor = int(input("Ingrese un número entero: "))
    cuadrado = valor * valor
    print(f"El cuadrado de {valor} es: {cuadrado}")

def calcularProducto():
    valor1 = int(input("Ingrese el primer número: "))
    valor2 = int(input("Ingrese el segundo número: "))
    producto = valor1 * valor2
    print(f"El producto de {valor1} y {valor2} es: {producto}")

calcularCuadrado()
calcularProducto()
