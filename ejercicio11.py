num1 = int(input("Ingrese el primer valor"))
num2 = int(input("Ingrese el segundo valor"))

if num1 > num2:
    print(f"La suma del los valores es {num1 + num2}")
    print(f"La diferencia del los valores es {num1 - num2}")
else:
    print(f"El producto de los valores es {num1 * num2}")
    print(f"La división de los dos valores es {num1 / num2}")

